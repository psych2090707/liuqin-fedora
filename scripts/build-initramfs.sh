usage() {
	cat <<'EOF'
usage: scripts/build-initramfs.sh [options]

  --out DIR              output root (default: <project>/out/boot); artifacts go
                         to DIR/initramfs/
  --kernel-out DIR       optional kernel build output directory; used for build
                         metadata only (include/config/kernel.release)
  --rootfs-manifest FILE assembled rootfs hash manifest; the Fedora admission
                         contract is generated from it via tools/build-root-contract.py
  --contract FILE        use an already generated contract (required with
                         --installer-overlay; contract v2 is embedded in both
                         the persistent and the RAM-installer ramdisk)
  --gnome-contract FILE  optional complete Fedora/GNOME v2 contract for a
                         transitional persistent boot; primary must be KDE.
                         Rejects simultaneous KDE/GDM enablement. No installer.
  --desktop kde|gnome    desktop topology for a contract generated from
                         --rootfs-manifest (default: $LIUQIN_DESKTOP or kde).
                         Use gnome after removing KDE; ignored with --contract.
  --privileges FILE      privileged-file expectations generated from the
                         assembled rootfs (setuid/setgid mode + capability
                         lines); required with --installer-overlay and embedded
                         as /etc/liuqin-installer-privileges
  --extra-pins-file FILE deprecated v1 flag; contract v2 has no content pins
                         and this option is rejected
  --firmware-pool DIR    firmware input pool (upstream build-liuqin-native-boot
                         layout: touch-nt36532/, bt-qca6490/, wlan-qca6490/,
                         regulatory/, gpu-adreno730/, dsp-sm8475/)
  --wlan-hsp2-tuple DIR  reviewed HSP2 WLAN tuple (hw2.0/ and hw2.1/)
  --audio-topology FILE  built AudioReach topology binary
  --busybox PATH         static aarch64 BusyBox (default: out/boot/toolchain/...)
  --slot-gcc PATH        aarch64 cross gcc for the static helpers
  --source-date-epoch N  fixed timestamp for cpio entries (default: 0)
  --allow-missing-firmware
                         build a structure-validation image without firmware
                         (dev images are NOT device-ready)
  --installer-overlay DIR
                         build the RAM-installer initramfs instead of the
                         persistent stage-1: DIR is the overlay produced by
                         installer/assemble-installer.py
                         (out/installer/image-overlay); storage mode is
                         read-only, /etc/liuqin-installer is written, and the contract v2
                         passed with --contract is embedded (install-root.sh
                         validates the extracted root against it)
  --extra-overlay DIR    copy this root-level tree into stage 1 (tar, modes and
                         symlinks preserved). Used for the distribution's own
                         Plymouth runtime; the init script starts it only when
