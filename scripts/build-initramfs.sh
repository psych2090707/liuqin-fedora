for applet in basename blockdev cat chmod chroot cp cttyhack cut dmesg findfs \
	grep hostname ip kill killall ln losetup ls mkdir mount poweroff readlink \
	reboot setsid sh sha256sum sleep stat switch_root sync telnetd udhcpd umount \
	rm mv cp rmdir mktemp tar uname stty tail head tr awk sed sort \
	uniq wc chown chgrp touch df du find xargs env date echo printf true \
	false test tee od base64 gzip zcat gunzip hexdump cmp diff \
	dirname realpath seq yes which id whoami free uptime; do
	# A repeated applet name (cp, cut, chmod, ...) is harmless: the first link wins.
	[ -e "$staging/bin/$applet" ] || ln -s busybox "$staging/bin/$applet"
done
