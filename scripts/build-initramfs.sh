  --allow-missing-pins   deprecated v1 flag (accepted as a no-op: contract v2
                         has no content pins)
  -h, --help             show this help

Firmware categories that are present are always digest-checked. Missing
categories are fatal unless --allow-missing-firmware is given; the omitted
categories are recorded in initramfs-info.json.

MACHINE INTERFACE (for scripts/build-bootimg.sh and the future kernel-install
hook that rebuilds boot.img after a kernel update):
  inputs      --out DIR, --kernel-out DIR (metadata only), --rootfs-manifest
              FILE or --contract FILE (required for the persistent image and
              --installer-overlay mode); --privileges FILE is required with
              --installer-overlay; --firmware-pool,
              --wlan-hsp2-tuple, --audio-topology, --busybox, --slot-gcc
  outputs     <--out>/initramfs/liuqin-firstboot.cpio.gz (+ contract,
              initramfs-info.json, SHA256SUMS, contiguous cpio listing)
  success     exit 0; stdout's last line is the absolute ramdisk path
  failure     1 = build/verify failure (do not use the ramdisk);
              2 = usage, missing-input or environment error
  determinism same inputs produce a byte-identical cpio.gz (SOURCE_DATE_EPOCH,
              sorted cpio, gzip -n)
  device_ready initramfs-info.json field "device_ready" is false when firmware
              categories are missing or the contract came from the synthetic
