stage_wlan() {
	# ath11k probes and boots MHI before /init can switch_root: stage-1-critical.
	wlan_root=$firmware_pool/wlan-qca6490
	wlan_board=$wlan_root/vendor/firmware_mnt/image/qca6490/bd_m81.elf
	wlan_dir=$wlan_root/upstream/WCN6855/hw2.0
	[ -d "$wlan_root" ] || { firmware_absent wlan "$wlan_root"; return; }
	[ -f "$wlan_board" ] || die "WLAN board data is missing: $wlan_board"
	[ -d "$wlan_dir" ] || die "upstream WCN6855 firmware directory is missing: $wlan_dir"
	[ "$(sha "$wlan_board")" = "$wlan_board_sha256" ] ||
		die "WLAN board data digest mismatch: $wlan_board"
	(cd "$wlan_dir" && printf '%s\n' "$wlan_firmware_sha256" | sha256sum -c --quiet -) ||
		die "upstream WCN6855 firmware does not match the pinned hashes: $wlan_dir"
	for revision in hw2.0 hw2.1; do
		mkdir -p "$staging/lib/firmware/ath11k/WCN6855/$revision"
		install -m 0644 "$wlan_board" \
			"$staging/lib/firmware/ath11k/WCN6855/$revision/board.bin"
	done
	printf '%s\n' "$wlan_firmware_sha256" | while read -r _ firmware_name; do
		install -m 0644 "$wlan_dir/$firmware_name" \
			"$staging/lib/firmware/ath11k/WCN6855/hw2.0/$firmware_name"
		ln -s "../hw2.0/$firmware_name" \
			"$staging/lib/firmware/ath11k/WCN6855/hw2.1/$firmware_name"
	done
	firmware_staged="$firmware_staged wlan"
}

stage_wlan_hsp2() {
	# The reviewed HSP2-amss20 tuple that passed upstream device validation.
	# Keep all four protocol inputs atomic and mirrored under updates/.
	if [ -z "$wlan_hsp2_tuple" ]; then
		if [ "$allow_missing_firmware" = 1 ]; then
			skip_firmware wlan-hsp2
			return
		fi
		die "the Fedora image requires the reviewed HSP2 WLAN tuple: pass --wlan-hsp2-tuple DIR"
	fi
	for revision in hw2.0 hw2.1; do
		[ -d "$wlan_hsp2_tuple/$revision" ] || die "HSP2 tuple lacks $revision: $wlan_hsp2_tuple"
		for item in \
			"amss.bin:$wlan_hsp2_amss_sha256" \
			"m3.bin:$wlan_hsp2_m3_sha256" \
			"board-2.bin:$wlan_hsp2_board2_sha256" \
			"regdb.bin:$wlan_hsp2_regdb_sha256"; do
			name=${item%%:*}
			want=${item#*:}
			file=$wlan_hsp2_tuple/$revision/$name
			[ -f "$file" ] || die "HSP2 tuple lacks $revision/$name"
			[ "$(sha "$file")" = "$want" ] || die "HSP2 tuple digest mismatch: $revision/$name"
			install -D -m 0644 "$file" \
				"$staging/lib/firmware/updates/ath11k/WCN6855/$revision/$name"
		done
	done
	firmware_staged="$firmware_staged wlan-hsp2"
}

