firmware_staged=
firmware_skipped=

skip_firmware() {
	# $1 = category
	case " $firmware_skipped " in
	*" $1 "*) ;;
	*) firmware_skipped="$firmware_skipped $1" ;;
	esac
	say "firmware: skipping category '$1'"
}

# ---------------------------------------------------------------------------
# 1. Quick preflight: BusyBox identity, init syntax, contract preparation
# ---------------------------------------------------------------------------
[ -f "$busybox" ] || die_usage "static aarch64 BusyBox is missing: $busybox (run tools/build-busybox.sh first)"
[ ! -L "$busybox" ] || die_usage "BusyBox must be a regular file: $busybox"
if ! LC_ALL=C readelf -h "$busybox" | grep -q 'Machine:.*AArch64'; then
	die_usage "BusyBox is not an AArch64 ELF: $busybox"
fi
if LC_ALL=C readelf -l "$busybox" | grep -q 'INTERP'; then
	die_usage "BusyBox is dynamically linked: $busybox"
fi
busybox_sha=$(sha "$busybox")

qemu=
for candidate in qemu-aarch64-static qemu-aarch64; do
	if command -v "$candidate" >/dev/null 2>&1; then
		qemu=$(command -v "$candidate")
		break
	fi
done
if [ -n "$qemu" ]; then
	"$qemu" "$busybox" sh -n "$source_dir/init" ||
		die "initramfs/init does not parse under the pinned BusyBox ash"
	say "init syntax ok under pinned BusyBox ash"
else
	say "warning: no qemu-aarch64 found; BusyBox ash syntax check skipped"
fi

# Contract v2 preparation: one generated/validated contract for BOTH the
# persistent boot image and the RAM installer (ADR-0004 D1/D4).  It is a
# topology contract -- no content pins of dnf-owned or user-editable files.
if [ -n "$rootfs_manifest" ] && [ -n "$contract" ]; then
	die "use --rootfs-manifest OR --contract, not both"
fi
contract_source=
if [ -n "$rootfs_manifest" ]; then
	[ -f "$rootfs_manifest" ] || die_usage "rootfs manifest is unavailable: $rootfs_manifest"
	set -- python3 "$project_root/tools/build-root-contract.py" \
		--manifest "$rootfs_manifest" --desktop "$desktop" --output "$contract_out"
	[ -z "$extra_pins_file" ] ||
		die_usage "--extra-pins-file is a v1 concept; contract v2 has no content pins (ADR-0004 D2)"
	[ "$allow_missing_pins" = 0 ] || set -- "$@" --allow-missing-pins
	"$@" || die "contract generation failed"
	contract_source=$rootfs_manifest
elif [ -n "$contract" ]; then
	[ -f "$contract" ] && [ ! -L "$contract" ] || die_usage "contract is unavailable or a symlink: $contract"
	cp -f "$contract" "$contract_out"
	say "using pre-generated contract: $contract"
else
	die_usage "a Fedora admission contract is required: pass --rootfs-manifest (assembled root hash manifest) or --contract"
fi
[ "$(stat -c '%a' "$contract_out")" = 644 ] || die "contract mode is not 644: $contract_out"
[ "$(head -n 1 "$contract_out")" = LIUQIN_FEDORA_ROOT_CONTRACT_V2 ] ||
	die "contract header is not LIUQIN_FEDORA_ROOT_CONTRACT_V2"
contract_size=$(stat -c '%s' "$contract_out")
[ "$contract_size" -ge 256 ] && [ "$contract_size" -le 16384 ] ||
	die "contract size is outside the stage-1 bounds (256..16384 bytes): $contract_size"
contract_lines=$(wc -l <"$contract_out")
[ "$contract_lines" -ge 8 ] && [ "$contract_lines" -le 128 ] ||
	die "contract line count is outside the stage-1 bounds (8..128): $contract_lines"
# Structural validation of the v2 grammar: header, then only the reviewed
# topology kinds with single-space fields (the boot parser splits on spaces).
awk '
	NR == 1 { if ($0 != "LIUQIN_FEDORA_ROOT_CONTRACT_V2") exit 1; next }
	/^#/ { next }
	$0 == "" { next }
	{
		kind = $1
		if (kind == "marker" && NF == 4) next
		if ((kind == "file" || kind == "exec" || kind == "display-manager") && NF == 2) next
		if (kind == "resolve" && NF == 3) next
		exit 1
	}
' "$contract_out" || die "contract has a line outside the v2 topology grammar"
contract_sha=$(sha "$contract_out")
if [ -n "$gnome_contract" ]; then
	[ -z "$installer_overlay" ] || die_usage "desktop transition is persistent-boot only; no installer"
	# The optional envelope admits only these two complete, reviewed routes.
	python3 - "$project_root" "$contract_out" "$gnome_contract" <<'PYCONTRACT'
import importlib.util
from pathlib import Path
import sys
spec = importlib.util.spec_from_file_location('contract', Path(sys.argv[1]) / 'tools/build-root-contract.py')
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
for desktop, path in zip(('kde', 'gnome'), sys.argv[2:]):
    p = Path(path)
    if p.is_symlink() or not p.is_file():
        raise SystemExit(f'Invalid {desktop} contract: {p}')
    if p.read_text() != m.build_contract_text(m.CONTRACT_HEADERS['fedora'], desktop):
        raise SystemExit(f'Transition requires the exact reviewed {desktop} topology: {p}')
PYCONTRACT
fi

# Privileged-file expectations (installer only): generated from the REAL
# assembled rootfs by scripts/build-image.sh; embed verbatim and validate its
# grammar here so a truncated/misspelled list dies at build time.
if [ -n "$installer_overlay" ]; then
	[ -f "$privileges" ] && [ ! -L "$privileges" ] ||
		die_usage "privileged-file expectations are unavailable: $privileges"
	privileges_sha=$(sha "$privileges")
	privileges_lines=$(grep -vc '^#' "$privileges" 2>/dev/null || true)
	case $privileges_lines in ''|*[!0-9]*) privileges_lines=0 ;; esac
	awk '
		/^#/ || $0 == "" { next }
		$1 == "setuid" || $1 == "setgid" { if (NF == 3 && $2 ~ /^[0-7]+$/ && $3 ~ /^\//) next; exit 1 }
		$1 == "cap" { if (NF == 3 && $3 ~ /^\//) next; exit 1 }
		{ exit 1 }
	' "$privileges" || die "privileged-file expectations have a malformed line"
	say "privileged-file expectations: $privileges_lines entries, sha256 $privileges_sha"
else
	contract_sha=$contract_sha
fi

# The synthetic example manifest is for offline structure validation only.  Say
# so loudly, in the log and in initramfs-info.json.
synthetic_contract=false
case $contract_source in
*tools/examples/*) synthetic_contract=true ;;
esac
if [ "$synthetic_contract" = true ]; then
	say "WARNING: contract was generated from the synthetic example manifest;"
	say "         this image is a structure-validation artifact, NOT device-ready"
fi

# ---------------------------------------------------------------------------
# 2. Stage directory skeleton and distribution-neutral files
# ---------------------------------------------------------------------------
mkdir -p "$staging/bin" "$staging/sbin" "$staging/etc" "$staging/proc" \
	"$staging/sys" "$staging/dev" "$staging/run" "$staging/usr/bin" \
	"$staging/usr/sbin"
install -m 0755 "$busybox" "$staging/bin/busybox"
install -m 0755 "$source_dir/init" "$staging/init"
install -m 0644 "$source_dir/etc/issue" "$staging/etc/issue"
install -m 0644 "$source_dir/etc/mdev.conf" "$staging/etc/mdev.conf"

# Optional root-level overlay (distribution packages copied verbatim). The
# early-Plymouth experiment uses it to carry the tablet's own plymouthd, its
# library closure and the stock themes; /init starts it only when the marker
# /etc/liuqin-early-plymouth is present, so other images are unaffected.
if [ -n "$extra_overlay" ]; then
	[ -d "$extra_overlay" ] || die_usage "--extra-overlay is not a directory: $extra_overlay"
