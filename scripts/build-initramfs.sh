# 4. Firmware (optional, digested when present)
#
# Presence policy: with --allow-missing-firmware a missing category is skipped
# and recorded (dev structure image); without it, a missing category is fatal.
# A *present* category is always digest-checked -- a wrong file is never
# silently accepted, in either mode.
# ---------------------------------------------------------------------------
firmware_absent() {
	# $1 = category, $2 = human-readable reason
	if [ "$allow_missing_firmware" = 1 ]; then
		skip_firmware "$1"
		# Must be 0: every caller is `[ -d ... ] || { firmware_absent ...; return; }`
		# under `set -eu`, so returning non-zero here aborted the whole build at
		# the first absent category — `--allow-missing-firmware` never produced a
		# partial-pool image (found while building a DSP-only pool).
		return 0
	fi
	die "firmware category '$1' is missing: $2 (pass --allow-missing-firmware only for dev structure images)"
}

