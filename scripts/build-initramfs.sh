# ---------------------------------------------------------------------------
# FEDORA: this list is what PATH resolves inside the RAM image.  The real
# tablet (2026-10-22) proved that a narrow list breaks the device-side
# installer scripts: `rm`, `mv`, `mktemp`, `stty`, `uname` and `tar` are called
