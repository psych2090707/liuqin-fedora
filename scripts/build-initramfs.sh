# Build the Fedora-fied liuqin stage-1 initramfs (PID 1 = /init, BusyBox ash).
#
# This replaces upstream xiaomipad-6pro-mainline tools/lib/build-initramfs.sh
# for the Fedora project.  It keeps the upstream *selection* of what must be
# inside stage 1 (static BusyBox, slot/charger helpers, touch/BT/WLAN/GPU/DSP/
# regulatory firmware, audio topology, marker files, root contract) and changes
# the packaging/distribution points:
#
#   * BusyBox comes from a pinned source build (tools/build-busybox.sh), never
#     from a distribution .deb/.rpm;
#   * the root profile is "fedora" and the admission contract is generated by
#     tools/build-root-contract.py from the assembled root's hash manifest;
#   * firmware inputs are optional for the offline/dev structure-validation
#     image (--allow-missing-firmware) but every supplied firmware file is
#     still checked against the upstream-pinned digests -- a wrong file is
#     always fatal, a missing category is only fatal in strict mode.
#
# Everything is offline: no device access, no boot partition write.
#
# Usage:
#   scripts/build-initramfs.sh \
#       --out out/boot \
#       --rootfs-manifest tools/examples/fedora-root.manifest.example \
#       --allow-missing-firmware
#
#   # production-shaped image (inputs from the user's own stock ROM/firmware):
#   scripts/build-initramfs.sh --out out/boot \
#       --rootfs-manifest out/rootfs/rootfs.hashes \
#       --firmware-pool /path/to/firmware-pool \
#       --wlan-hsp2-tuple /path/to/wlan-tuple \
#       --audio-topology /path/to/Xiaomi-Pad-6-Pro-tplg.bin
#
# Exit codes: 0 success; 1 build/verify failure; 2 usage or environment error.

