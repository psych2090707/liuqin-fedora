stage_bluetooth() {
	# btqca.c hardcodes the qca/ firmware prefix, so this directory is not a
	# choice.
	bt_dir=$firmware_pool/bt-qca6490/vendor/bt_firmware/image
	[ -d "$bt_dir" ] || { firmware_absent bluetooth "$bt_dir"; return; }
