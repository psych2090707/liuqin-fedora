"""Generate synthetic stock-ROM fixtures and run the extractor on them.

This is an *offline fixture generator* for manual inspection and integration
probes.  The images it writes are synthetic: they use the real Android on-disk
formats (DT table / vendor_boot v4 / boot image v2) but contain dummy FDT
payloads, not Xiaomi data.  They prove the parser/writer/layout plumbing; they
can never prove that the real ROM's 44 DTBO entries carry the 1781 ABL symbols.

Generated under <project>/out/stock-rom/selftest/ (git-ignored):

    synthetic-rom/images/{dtbo.img,vendor_boot.img,boot.img}
    inputs/                      full extractor output (both layouts + manifest)
    inputs/manifest.json
    release-boot-inspect.json    structure report of the cached published boot.img

Run: python3 tests/stock-rom/make-synthetic-fixtures.py [--out DIR]
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

TESTS = Path(__file__).resolve().parent
PROJECT = TESTS.parents[1]
CLI = PROJECT / "tools/extract-stock-rom-inputs.py"
PUBLISHED_BOOTIMG = PROJECT / "cache/upstream-v0.6.0/boot.img"


def load_test_module():
    spec = importlib.util.spec_from_file_location(
        "liuqin_stock_rom_tests", TESTS / "test-stock-rom.py")
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path,
                        default=PROJECT / "out/stock-rom/selftest",
                        help="output directory (default: out/stock-rom/selftest)")
    args = parser.parse_args()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)

    tests = load_test_module()
    rom = out / "synthetic-rom"
    if rom.exists():
        import shutil
        shutil.rmtree(rom)
    fixture = tests.make_rom_tree(rom)
    print(f"synthetic ROM: {rom} "
          f"(dtbo.img {len(fixture['dtbo'])} B, vendor_boot.img {len(fixture['vendor_boot'])} B, "
          f"boot.img {len(fixture['boot'])} B)")

    inputs = out / "inputs"
    if inputs.exists():
        import shutil
        shutil.rmtree(inputs)
    result = subprocess.run(
        [sys.executable, str(CLI), "--rom", str(rom), "--out", str(inputs),
         "--allow-outside", "--json"],
        text=True, capture_output=True, cwd=str(PROJECT))
    (out / "extract-run.log").write_text(
        f"exit={result.returncode}\n\nSTDOUT\n{result.stdout}\n\nSTDERR\n{result.stderr}\n")
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        return result.returncode
    manifest = json.loads(result.stdout)
    (out / "extract-summary.json").write_text(json.dumps({
        "counts": manifest["counts"],
        "rom_version_known": manifest["rom"]["version"]["known"],
        "warnings": manifest["warnings"],
        "notes": manifest["notes"],
        "layout_dirs": {name: tree for name, tree in
                        manifest["outputs"]["directories"].items()},
    }, indent=2, sort_keys=True) + "\n")

    verify = subprocess.run(
        [sys.executable, str(CLI), "--verify-manifest", "--out", str(inputs),
         "--allow-outside", "--json"],
        text=True, capture_output=True, cwd=str(PROJECT))
    (out / "verify-run.log").write_text(
        f"exit={verify.returncode}\n\nSTDOUT\n{verify.stdout}\n\nSTDERR\n{verify.stderr}\n")
    if verify.returncode != 0:
        print(verify.stderr, file=sys.stderr)
        return verify.returncode

    if PUBLISHED_BOOTIMG.is_file():
        inspect = subprocess.run(
            [sys.executable, str(CLI), "--inspect", str(PUBLISHED_BOOTIMG)],
            text=True, capture_output=True, cwd=str(PROJECT))
        if inspect.returncode == 0:
            (out / "release-boot-inspect.json").write_text(inspect.stdout)
            payload = json.loads(inspect.stdout)
            print(f"published boot.img: dtb {payload['header']['dtb_size']} B, "
                  f"sha256 {payload['dtb_sha256']}")

    (out / "README.txt").write_text(
        "Synthetic fixtures for tools/extract-stock-rom-inputs.py.\n\n"
        "These images use the REAL Android on-disk formats (DT table, vendor_boot\n"
        "header v4, boot image v2) but contain dummy FDT payloads. They are NOT a\n"
        "Xiaomi ROM and cannot prove real-ROM content (44 real DTBO entries / 14\n"
        "real base DTBs / 1781 ABL symbols). Generated by\n"
        "tests/stock-rom/make-synthetic-fixtures.py.\n")
    print(f"extractor output verified: {inputs}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
