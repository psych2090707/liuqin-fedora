#!/bin/sh
# SPDX-License-Identifier: MIT
#
# install-simulation.sh — REAL-product cross-check of the install delivery path.
#
# This does not trust any fixture: it takes the delivered bundle and simulates
# exactly what the RAM installer does with the objects it actually ships:
#
#   1. verify bundle.json/SHA256SUMS (the products are the ones that were built);
#   2. verify rootfs.tar.gz's real numeric owner/mode payload (privileged-file contract) and
#      flat layout; extract it onto a staging directory with the installer's own
#      tar flags (no /native-root level, flat install contract);
#   3. compare the extracted tree against the assembled root.img
#      (all paths+uid/gid/mode, every regular file against the shipped rootfs
#      hash manifest, plus a content sample read out of root.img itself);
#   4. run the Fedora admission predicate from the boot.img ramdisk against the
#      installed tree -- the SAME function/contract the tablet will run -- and
#      prove it rejects real topology breakage while accepting ordinary config
#      edits (topology contract);
#   5. check that boot.img and installer.img embed the identical contract v2
#      generated by tools/build-root-contract.py, and that the shipped
#      install-root.sh validates before the first write and installs FLAT with
#      plasmalogin (single-producer and flat install rules).
#
# The staging directory is a private scratch tree (--work).  NOTHING here opens
# a real block device or device partition.  The only block-like object is the
# delivered root.img, mounted read-only through fuse2fs and never written.
#
# Usage: tests/installer/install-simulation.sh --bundle DIR [--work DIR] [--keep]
# Exit codes: 0 = every check PASS; 1 = at least one FAIL; 2 = usage/input error.

set -eu

project_root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
bundle=
work_root=
keep=0
usage() {
	cat <<'EOF'
usage: tests/installer/install-simulation.sh --bundle DIR [--work DIR] [--keep]

  --bundle DIR   delivered bundle (root.img, rootfs.tar.gz, boot.img,
                 installer.img, bundle.json, SHA256SUMS, manifests/)
  --work DIR     scratch dir (default: <project>/out/install-sim/<UTC timestamp>)
  --keep         keep the extracted staging tree after a PASS
EOF
}
die() { printf 'install-simulation: %s\n' "$*" >&2; exit 2; }
say() { printf '\033[1;34m[install-simulation]\033[0m %s\n' "$*"; }
while [ "$#" -gt 0 ]; do
	case $1 in
	--bundle) [ "$#" -ge 2 ] && [ -n "$2" ] || die "--bundle needs a directory"; bundle=$2; shift ;;
	--work) [ "$#" -ge 2 ] && [ -n "$2" ] || die "--work needs a directory"; work_root=$2; shift ;;
	--keep) keep=1; shift ;;
	-h|--help) usage; exit 0 ;;
	*) die "unknown argument: $1 (see --help)" ;;
	esac
	shift
done
[ -n "$bundle" ] || { usage >&2; die "--bundle is required"; }
case $bundle in /*) ;; *) bundle=$project_root/$bundle ;; esac
[ -d "$bundle" ] || die "bundle is not a directory: $bundle"
case $bundle in */) bundle=${bundle%/} ;; esac

# fuse2fs mount and numeric-owner extraction need root.  Re-exec with the
# ALREADY RESOLVED arguments (the parser above consumed the originals).
if [ "$(id -u)" -ne 0 ]; then
	say "re-executing through sudo -n (root needed for numeric owner + ro fusermount)"
	set -- "$project_root/tests/installer/install-simulation.sh" --bundle "$bundle"
	[ -z "$work_root" ] || set -- "$@" --work "$work_root"
	[ "$keep" = 0 ] || set -- "$@" --keep
	exec sudo -n -- "$@"
fi

for tool in python3 tar gzip fuse2fs fusermount3 sha256sum find sort awk; do
	command -v "$tool" >/dev/null 2>&1 || die "missing host tool: $tool"
done
qemu=
for candidate in qemu-aarch64-static qemu-aarch64; do
	if command -v "$candidate" >/dev/null 2>&1; then qemu=$(command -v "$candidate"); break; fi
done
[ -n "$qemu" ] || die "qemu-aarch64(-static) is required to run the aarch64 initramfs init"

for payload in root.img rootfs.tar.gz boot.img installer.img bundle.json SHA256SUMS; do
	[ -f "$bundle/$payload" ] || die "bundle lacks $payload: $bundle"
done
[ -f "$bundle/manifests/rootfs.files.sha256" ] || die "bundle lacks manifests/rootfs.files.sha256"
[ -f "$bundle/manifests/liuqin-fedora-root.contract" ] || die "bundle lacks manifests/liuqin-fedora-root.contract"

if [ -z "$work_root" ]; then
	work_root=$project_root/out/install-sim/$(date -u '+%Y%m%dT%H%M%SZ')
fi
case $work_root in /*) ;; *) work_root=$project_root/$work_root ;; esac
mkdir -p "$work_root"
if [ -e "$work_root/staging" ]; then
	die "work directory already holds a staging tree: $work_root (use a new --work)"
fi
staging=$work_root/staging
mnt=$work_root/rootimg-mnt
ramdisk_boot=$work_root/boot-ramdisk
ramdisk_installer=$work_root/installer-ramdisk
checks_tsv=$work_root/checks.tsv
: >"$checks_tsv"
check() { # check <id> <PASS|FAIL> <detail>
	printf '%s\t%s\t%s\n' "$1" "$2" "$3" >>"$checks_tsv"
	if [ "$2" = PASS ]; then
		printf 'PASS %-42s %s\n' "$1" "$3"
	else
		printf 'FAIL %-42s %s\n' "$1" "$3"
	fi
}
failed=0
pass() { check "$1" PASS "${2:-}"; }
fail() { check "$1" FAIL "${2:-}"; failed=$((failed + 1)); }

mounted=0
cleanup() {
	set +e
	if [ "$mounted" = 1 ]; then
		fusermount3 -u "$mnt" 2>/dev/null || fusermount -u "$mnt" 2>/dev/null || true
		mounted=0
	fi
}
trap cleanup EXIT HUP INT TERM

# ---------------------------------------------------------------------------
# 1. The products really are the ones bundle.json describes.
# ---------------------------------------------------------------------------
say "verifying bundle checksums: $bundle"
if (cd "$bundle" && sha256sum -c SHA256SUMS >/dev/null 2>&1); then
	pass bundle.checksums "sha256sum -c SHA256SUMS"
else
	fail bundle.checksums "sha256sum -c SHA256SUMS failed"
fi
bundle_json_check=$(python3 - "$bundle" <<'PY'
import hashlib
import json
import sys
from pathlib import Path

bundle = Path(sys.argv[1])
data = json.loads((bundle / 'bundle.json').read_text())
problems = []
for name, want in (data.get('files') or {}).items():
    path = bundle / name
    if not path.is_file():
        problems.append('missing ' + name)
        continue
    got = hashlib.sha256(path.read_bytes()).hexdigest()
    if got != want:
        problems.append('sha256 mismatch ' + name)
if data.get('device') != 'liuqin':
    problems.append('device is not liuqin')
if data.get('device_ready') is not False:
    problems.append('offline bundle must keep device_ready=false')
print('; '.join(problems))
raise SystemExit(1 if problems else 0)
PY
) || true
if [ -z "$bundle_json_check" ]; then
	pass bundle.json "bundle.json payload sha256s match, device_ready=false"
else
	fail bundle.json "$bundle_json_check"
fi
bundle_device_ready=$(python3 - "$bundle/bundle.json" <<'PY'
import json, sys
print('true' if json.load(open(sys.argv[1])).get('device_ready') else 'false')
PY
)
reasons=$(python3 - "$bundle/bundle.json" <<'PY'
import json, sys
print(len(json.load(open(sys.argv[1])).get('device_ready_reasons') or []))
PY
)
pass bundle.device_ready "device_ready=$bundle_device_ready with $reasons honest reasons (offline bundle)"

# ---------------------------------------------------------------------------
# 2. rootfs.tar.gz: flat layout + real numeric owner/mode acceptance (D3).
# ---------------------------------------------------------------------------
tarfile=$bundle/rootfs.tar.gz
say "checking rootfs.tar.gz layout and metadata"
tar -tzf "$tarfile" >"$work_root/rootfs.entries" 2>"$work_root/tar-list.err" || {
	fail tar.readable "rootfs.tar.gz is not a readable tar.gz"
	cat "$work_root/tar-list.err" >&2 || true
}
if [ -s "$work_root/rootfs.entries" ]; then
	pass tar.readable "rootfs.tar.gz is a readable tar.gz"
	if grep -q '^\./native-root' "$work_root/rootfs.entries"; then
		fail tar.flat "archive still carries the obsolete native-root/ level (D4)"
	else
		pass tar.flat "flat archive root (no native-root/ level)"
	fi
	tar_meta=$(python3 - "$tarfile" <<'PY'
import sys
import tarfile

WANT = {
    './home/user': (1000, 1000, 0o700),
    './usr/bin/plasmashell': (0, 0, 0o755),
    './usr/bin/plasmalogin': (0, 0, 0o755),
    './usr/bin/mount': (0, 0, 0o4755),
    './usr/bin/sudo': (0, 0, 0o4111),
    './etc/liuqin-fedora-root': (0, 0, 0o644),
}
found = {}
with tarfile.open(sys.argv[1], 'r:gz') as archive:
    for member in archive:
        if member.name in WANT and member.name not in found:
            found[member.name] = member
        if len(found) == len(WANT):
            break
problems = []
for name, want in WANT.items():
    member = found.get(name)
    if member is None:
        problems.append(name + ' missing')
        continue
    got = (member.uid, member.gid, member.mode & 0o7777)
    if got != want:
        problems.append(f'{name} uid/gid/mode {got} != {want}')
print('; '.join(problems))
raise SystemExit(1 if problems else 0)
PY
) || true
	if [ -z "$tar_meta" ]; then
		pass tar.metadata "/home/user=1000:1000 0700, plasmashell=0755, mount=04755, sudo=04111, marker=0644"
	else
		fail tar.metadata "$tar_meta"
	fi
fi

# ---------------------------------------------------------------------------
# 3. Extract with the installer's own tar flags (flat, numeric owner, ACL/xattr).
# ---------------------------------------------------------------------------
say "extracting rootfs.tar.gz with the installer's tar flags onto staging"
mkdir -p "$staging"
if tar -xzf "$tarfile" -C "$staging" --numeric-owner --same-owner --same-permissions \
	--acls --xattrs --xattrs-include='*' --warning=no-timestamp; then
	pass extract.flat "tar -xzf onto the staging root (no intermediate directory)"
else
	fail extract.flat "tar extraction failed"
	die "cannot continue without a staging tree"
fi
[ ! -e "$staging/native-root" ] && pass extract.no_native_root "no native-root directory was created" ||
	fail extract.no_native_root "extraction created a native-root directory"
# The installer-owned files it is allowed to write are not in the archive content
# checks: fstab/machine-id/random-seed are validated in step 6.

# ---------------------------------------------------------------------------
# 4. The extracted tree equals the shipped rootfs manifest (every file).
# ---------------------------------------------------------------------------
say "verifying every extracted file against manifests/rootfs.files.sha256"
manifest_result=$(python3 - "$bundle/manifests/rootfs.files.sha256" "$staging" <<'PY'
import hashlib
import sys
from pathlib import Path

manifest, root = Path(sys.argv[1]), Path(sys.argv[2])
checked = 0
missing = []
mismatched = []
for raw in manifest.read_text(encoding='utf-8', errors='surrogateescape').splitlines():
    digest, sep, rel = raw.partition('  ')
    if not sep or not rel.startswith('/'):
        continue
    path = root / rel.lstrip('/')
    if not path.is_file() or path.is_symlink():
        missing.append(rel)
        if len(missing) >= 10:
            break
        continue
    stream = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            stream.update(chunk)
    if stream.hexdigest() != digest:
        mismatched.append(rel)
        if len(mismatched) >= 10:
            break
    checked += 1
status = 'ok' if not (missing or mismatched) else 'fail'
print(f'{status} checked={checked} missing={len(missing)} mismatched={len(mismatched)} '
      + (' '.join(missing + mismatched)))
raise SystemExit(0 if status == 'ok' else 1)
PY
) || true
case $manifest_result in
ok\ checked=*) pass rootfs.manifest "${manifest_result#ok }" ;;
*) fail rootfs.manifest "manifest verification failed: $manifest_result" ;;
esac

# ---------------------------------------------------------------------------
# 5. root.img: read-only mount, label, flat layout, metadata and content sample.
# ---------------------------------------------------------------------------
say "mounting a private copy of root.img read-only through fuse2fs"
# Never mount the delivered root.img: even a read-only fuse2fs mount can touch
# ext4 metadata (last-mount counters/journal), which would silently change the
# sha256 that bundle.json/SHA256SUMS record for the delivered artifact.
rootimg_copy=$work_root/root.img.verify
cp --reflink=auto --sparse=always "$bundle/root.img" "$rootimg_copy" ||
	die "could not create a private copy of root.img for verification"
mkdir -p "$mnt"
if fuse2fs -o ro "$rootimg_copy" "$mnt" 2>"$work_root/fuse2fs.err"; then
	mounted=1
	pass rootimg.mount "fuse2fs read-only mount of a private root.img copy"
else
	fail rootimg.mount "could not mount root.img read-only (see $work_root/fuse2fs.err)"
fi
if [ "$mounted" = 1 ]; then
	label=$(blkid -p -s LABEL -o value "$rootimg_copy" 2>/dev/null || true)
	[ "$label" = LIUQIN_ROOT ] && pass rootimg.label "LABEL=LIUQIN_ROOT" ||
		fail rootimg.label "label is '$label', expected LIUQIN_ROOT"
	[ -d "$mnt/etc" ] && [ -d "$mnt/usr" ] && [ ! -e "$mnt/native-root" ] &&
		pass rootimg.flat "root.img root IS the rootfs root (no native-root/ level)" ||
		fail rootimg.flat "root.img is not a flat rootfs"
	# Full path+type+uid/gid+mode comparison between root.img and the extracted tar.
	(
		cd "$mnt" && find . -path ./lost+found -prune -o -printf '%P\t%y\t%m\t%u\t%g\n' |
			LC_ALL=C sort
	) >"$work_root/rootimg.meta"
	(
		cd "$staging" && find . -printf '%P\t%y\t%m\t%u\t%g\n' | LC_ALL=C sort
	) >"$work_root/staging.meta"
	if cmp -s "$work_root/rootimg.meta" "$work_root/staging.meta"; then
		pass rootimg.metadata "every path/type/mode/uid/gid in root.img equals the extracted tar ($(wc -l <"$work_root/rootimg.meta") entries)"
	else
		diff_out=$work_root/rootimg-vs-staging.diff
		diff -u "$work_root/rootimg.meta" "$work_root/staging.meta" >"$diff_out" 2>&1 || true
		fail rootimg.metadata "root.img metadata differs from the extracted tar ($(grep -c '^[+-]' "$diff_out" || true) diff lines; see $diff_out)"
	fi
	# Content sample read out of the root image itself: key files + every 97th
	# manifest entry, so the check is not limited to metadata.
	content_sample=$(python3 - "$bundle" "$mnt" <<'PY'
import hashlib
import sys
from pathlib import Path

bundle, mnt = Path(sys.argv[1]), Path(sys.argv[2])
KEY = {
    '/etc/os-release', '/etc/liuqin-fedora-root', '/etc/liuqin/image-contract',
    '/etc/fstab', '/usr/lib/systemd/system/plasmalogin.service',
    '/usr/bin/plasmashell', '/usr/bin/plasmalogin', '/usr/lib/systemd/systemd',
    '/usr/share/liuqin/kernel.release', '/usr/share/liuqin/rootfs.files.sha256',
}
entries = []
for raw in (bundle / 'manifests/rootfs.files.sha256').read_text(
        encoding='utf-8', errors='surrogateescape').splitlines():
    digest, sep, rel = raw.partition('  ')
    if sep and rel.startswith('/'):
        entries.append((rel, digest))
chosen = [item for item in entries if item[0] in KEY]
chosen += [entries[i] for i in range(0, len(entries), max(1, len(entries) // 200))][:220]
problems = []
checked = 0
seen = set()
for rel, digest in chosen:
    if rel in seen:
        continue
    seen.add(rel)
    path = mnt / rel.lstrip('/')
    if not path.is_file():
        problems.append('root.img missing ' + rel)
        if len(problems) >= 10:
            break
        continue
    stream = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            stream.update(chunk)
    if stream.hexdigest() != digest:
        problems.append('content mismatch ' + rel)
        if len(problems) >= 10:
            break
    checked += 1
print(f'checked={checked} problems={len(problems)} ' + ' '.join(problems))
raise SystemExit(1 if problems else 0)
PY
	) || true
	case $content_sample in
	checked=*problems=0*) pass rootimg.content "root.img content sample: ${content_sample#checked=}" ;;
	*) fail rootimg.content "root.img content sample failed: $content_sample" ;;
	esac
fi

# ---------------------------------------------------------------------------
# 6. boot.img / installer.img: identical embedded contract v2 and real ramdisks.
# ---------------------------------------------------------------------------
unpack_ramdisk() { # <boot.img> <out dir>
	python3 - "$1" "$2" <<'PY'
import gzip
import struct
import sys
from pathlib import Path

image, out = Path(sys.argv[1]), Path(sys.argv[2])
data = image.read_bytes()
header = data[:2048]
if header[:8] != b'ANDROID!':
    raise SystemExit(str(image) + ' is not an Android boot image')
page_size = struct.unpack_from('<I', header, 36)[0] or 4096
kernel_size = struct.unpack_from('<I', header, 8)[0]
ramdisk_size = struct.unpack_from('<I', header, 16)[0]

def align(value):
    return (value + page_size - 1) // page_size * page_size

offset = page_size + align(kernel_size)
ramdisk = data[offset:offset + ramdisk_size]
if len(ramdisk) != ramdisk_size:
    raise SystemExit('ramdisk is truncated')
cpio = gzip.decompress(ramdisk)
pos = 0
out.mkdir(parents=True, exist_ok=True)
while cpio[pos:pos + 6] in (b'070701', b'070702'):
    fields = [int(cpio[pos + 6 + i * 8: pos + 14 + i * 8], 16) for i in range(13)]
    namesize, filesize, mode = fields[11], fields[6], fields[1]
    name = cpio[pos + 110: pos + 110 + namesize - 1].decode('utf-8', 'replace')
    start = (pos + 110 + namesize + 3) // 4 * 4
    body = cpio[start:start + filesize]
    target = out / name.lstrip('./')
    if name.endswith('/') or (mode & 0o170000) == 0o040000:
        target.mkdir(parents=True, exist_ok=True)
    elif (mode & 0o170000) == 0o120000:
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            target.symlink_to(body.decode('utf-8', 'replace'))
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(body)
        target.chmod(mode & 0o7777)
    pos = (start + filesize + 3) // 4 * 4
PY
}

want_contract=$bundle/manifests/liuqin-fedora-root.contract
say "unpacking boot.img / installer.img ramdisks"
if unpack_ramdisk "$bundle/boot.img" "$ramdisk_boot" 2>"$work_root/boot-unpack.err" &&
	[ -f "$ramdisk_boot/etc/liuqin-fedora-root.contract" ] &&
	[ -f "$ramdisk_boot/init" ] && [ -f "$ramdisk_boot/bin/busybox" ]; then
	pass boot.ramdisk "boot.img ramdisk carries init, busybox and the admission contract"
	if cmp -s "$ramdisk_boot/etc/liuqin-fedora-root.contract" "$want_contract"; then
		pass boot.contract_embedded "boot.img contract is byte-identical to the bundle/generator contract"
	else
		fail boot.contract_embedded "boot.img contract differs from the bundle contract"
	fi
else
	fail boot.ramdisk "could not unpack the boot.img ramdisk (see $work_root/boot-unpack.err)"
fi
if unpack_ramdisk "$bundle/installer.img" "$ramdisk_installer" 2>"$work_root/installer-unpack.err" &&
	[ -f "$ramdisk_installer/etc/liuqin-fedora-root.contract" ] &&
	[ -f "$ramdisk_installer/usr/lib/liuqin/install-root.sh" ]; then
	pass installer.ramdisk "installer.img ramdisk carries install-root.sh and the admission contract"
	if cmp -s "$ramdisk_installer/etc/liuqin-fedora-root.contract" "$want_contract"; then
		pass installer.contract_embedded "installer.img contract is byte-identical to the boot.img/bundle contract (single producer)"
	else
		fail installer.contract_embedded "installer.img contract differs from the bundle contract"
	fi
	installed_script=$ramdisk_installer/usr/lib/liuqin/install-root.sh
	# The shipped installer must validate the contract before the first write and
	# install FLAT with plasmalogin (flat install contract): check the real shipped script.
	if grep -q 'contract_validate$' "$installed_script" &&
		[ "$(grep -n 'contract_validate$' "$installed_script" | head -1 | cut -d: -f1)" -lt \
			"$(grep -n 'blockdev --setrw' "$installed_script" | head -1 | cut -d: -f1)" ]; then
		pass installer.pre_write_validation "contract_validate runs before the first blockdev --setrw"
	else
		fail installer.pre_write_validation "contract_validate is missing or runs after the first write"
	fi
	if grep -q 'tar -xzf "\$archive" -C /mnt/install ' "$installed_script" &&
		! grep -q 'mkdir /mnt/install/native-root' "$installed_script" &&
		grep -q 'enable_unit "\$1" plasmalogin.service' "$installed_script" &&
		! grep -q 'enable_unit "\$1" sddm.service' "$installed_script"; then
		pass installer.flat_plasmalogin "flat extraction (-C /mnt/install), plasmalogin enabled, no SDDM enable path"
	else
		fail installer.flat_plasmalogin "installer is not the flat/plasmalogin Fedora path"
	fi
	# Execute the SHIPPED install-root.sh installation-time
	# validation functions (contract_validate, fedora_privileged_files,
	# contract_apply) against the REAL installed tar tree instead of grepping the
	# shipped script text.  The functions are extracted VERBATIM from the shipped
	# script; only absolute mount paths are redirected to the staging tree (the
	# same technique test-install-root.sh uses), so the executing code is the
	# code the tablet runs.
	priv_helper=$ramdisk_installer/usr/lib/liuqin/install-privileges.sh
	priv_expect=$ramdisk_installer/etc/liuqin-installer-privileges
	harness=$work_root/shipped-install-checks.sh
	shipped_log=$work_root/shipped-install-checks.log
	: >"$shipped_log"
	if python3 - "$installed_script" "$ramdisk_installer" "$staging" "$harness" <<'PYH'
import re
import shlex
import sys

shipped, ramdisk, target, out = sys.argv[1:5]
lines = open(shipped, encoding="utf-8", errors="surrogateescape").read().splitlines()
wanted = ["die", "contract_die", "contract_normalize_path", "contract_resolve_path",
          "contract_owned_regular", "contract_executable", "contract_login_manager_ok",
          "contract_validate", "contract_apply"]
blocks = {}
i = 0
while i < len(lines):
    match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\(\) \{", lines[i])
    if match and match.group(1) in wanted and match.group(1) not in blocks:
        name = match.group(1)
        depth = 0
        j = i
        while j < len(lines):
            depth += lines[j].count("{") - lines[j].count("}")
            if depth <= 0:
                break
            j += 1
        blocks[name] = "\n".join(lines[i:j + 1])
        i = j + 1
        continue
    i += 1
missing = [name for name in wanted if name not in blocks]
if missing:
    raise SystemExit("shipped install-root.sh lacks functions: " + ", ".join(missing))
body = ["#!/bin/sh", "set -eu"]
body += [blocks[name] for name in wanted]
contract = ramdisk + "/etc/liuqin-fedora-root.contract"
privileges = ramdisk + "/etc/liuqin-installer-privileges"
helper = ramdisk + "/usr/lib/liuqin/install-privileges.sh"
body.append("CONTRACT_FILE=" + shlex.quote(contract))
body.append(". " + shlex.quote(helper))
body.append("TARGET=" + shlex.quote(target))
body.append("EXPECTATIONS=" + shlex.quote(privileges))
body += [
    'case ${SHIPPED_CHECK_MODE:-all} in',
    'contract) contract_validate; contract_apply "$TARGET" ;;',
    'privileges) fedora_privileged_files "$TARGET" "$EXPECTATIONS" ;;',
    'all) contract_validate; fedora_privileged_files "$TARGET" "$EXPECTATIONS"; '
    'contract_apply "$TARGET"; printf "shipped-install-checks: PASS\\n" ;;',
    '*) echo "unknown SHIPPED_CHECK_MODE" >&2; exit 2 ;;',
    'esac',
]
open(out, "w").write("\n".join(body) + "\n")
print("shipped-install-checks harness: " + ", ".join(wanted))
PYH
	then
		pass installer.shipped_harness \
			"shipped install-root.sh validation functions extracted from installer.img"
		run_shipped() { # <all|contract|privileges>
			SHIPPED_CHECK_MODE=$1 sh "$harness" >>"$shipped_log" 2>&1
		}
		priv_entries=$(grep -vc '^#' "$priv_expect" || true)
		priv_caps=$(awk '$1 == "cap"' "$priv_expect" | wc -l)
		image_sha=$(sha256sum "$bundle/installer.img" | cut -d' ' -f1)
		pass installer.privileges_embedded \
			"installer.img ships the derived validator + $priv_entries expectations ($priv_caps capability files), sha256=$image_sha"
		# 1) full shipped install-time validation path on the real tree
		if run_shipped all; then
			pass installer.shipped_functions \
				"shipped contract_validate + fedora_privileged_files + contract_apply PASS on the real tar tree"
		else
			fail installer.shipped_functions \
				"shipped install-root.sh validation functions reject the real tar tree (see $shipped_log)"
		fi
		# 2) shipped privileged validator on the real tree
		if run_shipped privileges; then
			pass privileges.real_tree \
				"shipped validator accepts the real installed tree (setuid/setgid + capabilities preserved by tar)"
		else
			fail privileges.real_tree "shipped privileged validator rejects the real tree (see $shipped_log)"
		fi
		# Real Fedora 44 ping has no capability; requiring one was the required bug.
		if grep -q '^cap .* /usr/bin/ping$' "$priv_expect"; then
			fail privileges.no_hardcoded_ping "expectations still require a ping capability"
		else
			pass privileges.no_hardcoded_ping "no ping capability is required (derived list only)"
		fi
		# 3) negative control: strip a build-time capability from the real tree
		cap_path=$(awk '$1 == "cap" { print $3; exit }' "$priv_expect")
		if [ -n "$cap_path" ]; then
			cp -a "$staging$cap_path" "$work_root/cap-file.bak"
			python3 - "$staging$cap_path" <<'PYNCAP'
import os
import sys
os.removexattr(sys.argv[1], b'security.capability')
PYNCAP
			if run_shipped privileges; then
				fail privileges.negative_cap \
					"a capability stripped from the installed tree was accepted ($cap_path)"
			else
				pass privileges.negative_cap \
					"stripped capability on $cap_path is rejected by the shipped install-root.sh path"
			fi
			cp -a "$work_root/cap-file.bak" "$staging$cap_path"
			if run_shipped privileges; then
				pass privileges.restored "validator PASS after restoring the capability"
			else
				fail privileges.restored "validator still rejects after restoring the capability"
			fi
		else
			fail privileges.negative_cap "no capability entry in the expectations to strip"
		fi
		# 4) negative control: topology breakage must be rejected by the SHIPPED
		#    contract_apply (install-time path, not the boot initramfs).
		chmod 0644 "$staging/usr/bin/plasmashell"
		if run_shipped contract; then
			fail installer.shipped_contract_negative \
				"shipped contract_apply accepted a non-executable plasmashell"
		else
			pass installer.shipped_contract_negative \
				"shipped contract_apply rejects a non-executable plasmashell on the real tree"
		fi
		chmod 0755 "$staging/usr/bin/plasmashell"
		if run_shipped contract; then
			pass installer.shipped_contract_restored \
				"shipped contract_apply PASS after restoring the real topology"
		else
			fail installer.shipped_contract_restored \
				"shipped contract_apply still rejects after restoring the real topology"
		fi
	else
		fail installer.shipped_harness \
			"could not extract the shipped install-root.sh validation functions (see $shipped_log)"
	fi
else
	fail installer.ramdisk "could not unpack the installer.img ramdisk (see $work_root/installer-unpack.err)"
fi

# ---------------------------------------------------------------------------
# 7. Boot admission predicate from the real boot.img against the install tree.
# ---------------------------------------------------------------------------
run_admission() { # <root> <log> -> rc
	env \
		LIUQIN_INIT_STORAGE_TEST_ONLY=1 \
		LIUQIN_INIT_TEST_BUSYBOX="$ramdisk_boot/bin/busybox" \
		LIUQIN_INIT_TEST_PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \
		LIUQIN_INIT_TEST_LOG="$2" \
		LIUQIN_STORAGE_FEDORA_CONTRACT="$ramdisk_boot/etc/liuqin-fedora-root.contract" \
		LIUQIN_INIT_ADMISSION_ROOT="$1" \
		"$qemu" "$ramdisk_boot/bin/busybox" sh "$ramdisk_boot/init"
}
restore_tree_state() {
	chmod 755 "$staging/usr/bin/plasmashell"
	ln -sfn /usr/lib/systemd/system/plasmalogin.service "$staging/etc/systemd/system/display-manager.service"
}

say "running the real boot.img admission predicate against the install tree"
admission_log=$work_root/admission-pass.log
if run_admission "$staging" "$admission_log"; then
	pass admission.pass "boot.img init storage_fedora_root_ok() accepts the installed tar tree"
else
	fail admission.pass "boot.img init rejects the installed tar tree (see $admission_log)"
fi

# 7a. Real product D2 proof: ordinary config edits must NOT be rejected.
mutable_backup=$work_root/mutable-backup
mkdir -p "$mutable_backup"
for mutable in etc/hostname etc/locale.conf etc/fstab etc/selinux/config; do
	[ -f "$staging/$mutable" ] || continue
	mkdir -p "$mutable_backup/$(dirname "$mutable")"
	cp -a "$staging/$mutable" "$mutable_backup/$mutable"
done
{
	printf 'edited-hostname\n' >>"$staging/etc/hostname" 2>/dev/null || true
	printf 'LANG=de_DE.UTF-8\n' >>"$staging/etc/locale.conf" 2>/dev/null || true
	printf '# edited by install-simulation: this line must not break admission\n' \
		>>"$staging/etc/fstab"
} 2>/dev/null || true
mutable_log=$work_root/admission-mutable-edits.log
if run_admission "$staging" "$mutable_log"; then
	pass admission.mutable_config "hostname/locale/fstab edits still boot (topology contract-C: no content pins)"
else
	fail admission.mutable_config "ordinary config edits were rejected at admission (v1-like content pin behaviour)"
fi
for mutable in etc/hostname etc/locale.conf etc/fstab etc/selinux/config; do
	[ -f "$mutable_backup/$mutable" ] || continue
	cp -a "$mutable_backup/$mutable" "$staging/$mutable"
done

# 7b. Real topology breakage must be rejected.
chmod 644 "$staging/usr/bin/plasmashell" 2>/dev/null || true
broken_exec_log=$work_root/admission-broken-exec.log
if run_admission "$staging" "$broken_exec_log"; then
	fail admission.topology_exec "removing the plasmashell exec bit was accepted"
else
	pass admission.topology_exec "non-executable plasmashell is rejected (D2-B topology gate is live)"
fi
chmod 755 "$staging/usr/bin/plasmashell"
rm -f "$staging/etc/systemd/system/display-manager.service"
broken_dm_log=$work_root/admission-broken-dm.log
if run_admission "$staging" "$broken_dm_log"; then
	fail admission.topology_login_manager "a missing display-manager resolution was accepted"
else
	pass admission.topology_login_manager "missing login-manager resolution is rejected (D2-B is live)"
fi
restore_tree_state
final_log=$work_root/admission-restored.log
if run_admission "$staging" "$final_log"; then
	pass admission.restored "admission PASS after restoring the real topology"
else
	fail admission.restored "admission FAIL after restoring the tree (see $final_log)"
fi

# ---------------------------------------------------------------------------
# 8. Report
# ---------------------------------------------------------------------------
cleanup
trap - EXIT HUP INT TERM
report=$work_root/report.json
python3 - "$checks_tsv" "$report" "$bundle" <<'PY'
import json
import sys
from pathlib import Path

tsv, report, bundle = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
checks = []
for line in tsv.read_text().splitlines():
    parts = line.split('\t')
    if len(parts) < 3:
        continue
    checks.append({'id': parts[0], 'status': parts[1], 'detail': '\t'.join(parts[2:])})
counts = {status: sum(1 for c in checks if c['status'] == status)
          for status in ('PASS', 'FAIL')}
result = 'FAIL' if counts['FAIL'] else 'PASS'
report.write_text(json.dumps({
    'format': 'liuqin-install-simulation/v1',
    'bundle': str(bundle),
    'working_directory': str(tsv.parent),
    'simulated': 'rootfs.tar.gz extracted with the installer tar flags onto a staging root, '
                 'compared with root.img and admitted by the boot.img init predicate; '
                 'no real block device or partition was opened',
    'summary': {**counts, 'total': len(checks), 'result': result},
    'checks': checks,
}, indent=2) + '\n')
print(f"install-simulation: {result} ({counts['PASS']} PASS / {counts['FAIL']} FAIL) -> {report}")
raise SystemExit(0 if result == 'PASS' else 1)
PY
if [ "$keep" = 1 ]; then
	say "kept staging tree: $staging"
else
	say "staging tree kept under $work_root (delete it manually when done)"
